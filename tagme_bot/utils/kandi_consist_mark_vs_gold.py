# ─── Вспомогательные функции для работы с изображениями ─────────────────

_img_cache = {}
_img_lock = threading.Lock()


def _is_internal_tagme_url(u: str) -> bool:
    """Проверяет, является ли URL приватной TagMe-ссылкой."""
    u = (u or '').lower()
    return 'tagme.sberdevices.ru' in u or 'tagme.ift.delta.sbrf.ru' in u


def get_image_data_url(url: str, max_bytes: int = None) -> str:
    """
    Скачивает изображение и возвращает data:image/jpeg;base64,...

    Лимит прокси на JSON ~0.5 МБ, поэтому картинку ужимаем до max_bytes.
    Результат кешируется, потокобезопасно.
    """
    if max_bytes is None:
        max_bytes = IMG_MAX_BYTES

    url = (url or '').strip()
    if url.startswith('data:image/'):
        return url

    with _img_lock:
        if url in _img_cache:
            return _img_cache[url]

    headers = {}
    if _is_internal_tagme_url(url):
        if get_proxy_token is None:
            raise RuntimeError('приватная TagMe-ссылка, но get_proxy_token недоступен')
        cfg_path = IMAGE_PROXY_CFG_PATH or DEFAULT_PROXY_CFG_PATH
        headers['Authorization'] = f'Bearer {get_proxy_token(cfg_path)}'

    r = requests.get(url, headers=headers, timeout=IMG_TIMEOUT, verify=False)
    r.raise_for_status()

    try:
        img = Image.open(BytesIO(r.content)).convert('RGB')
    except Exception as e:
        ctype = r.headers.get('Content-Type', '?')
        raise RuntimeError(
            f'ответ не является картинкой (Content-Type={ctype}, '
            f'{len(r.content)} байт): {e}'
        )

    # Ужимаем до нужного размера
    data = b''
    for side, q in [(1024, 80), (1024, 65), (768, 65), (512, 60), (384, 50)]:
        im = img.copy()
        im.thumbnail((side, side))
        buf = BytesIO()
        im.save(buf, 'JPEG', quality=q)
        data = buf.getvalue()
        if len(data) <= max_bytes:
            break

    data_url = 'data:image/jpeg;base64,' + base64.b64encode(data).decode('ascii')

    with _img_lock:
        _img_cache[url] = data_url

    return data_url


# ─── Вспомогательные функции ─────────────────────────────────────────────

def _get(data: dict, *keys: str, default: Any = None) -> Any:
    """Ищет значение по нескольким возможным именам ключа (алиасам)."""
    for key in keys:
        if key in data and data[key] not in (None, ""):
            return data[key]
    return default


def _flag(value: Any) -> bool:
    """Приводит значение поля *_broken к bool (как _flag в ноутбуке)."""
    return str(value).strip().lower() in ("true", "1", "1.0", "да")


def _load_json_loose(content: str) -> Optional[dict]:
    """Пытается распарсить JSON-объект из ответа LLM (в т.ч. в ```-обёртке)."""
    if not content:
        return None
    text = content.strip()
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*", "", text)
        text = re.sub(r"\s*```$", "", text)
    try:
        parsed = json.loads(text.strip())
        return parsed if isinstance(parsed, dict) else None
    except Exception:
        m = re.search(r"\{.*\}", text, re.DOTALL)
        if not m:
            return None
        try:
            parsed = json.loads(m.group())
            return parsed if isinstance(parsed, dict) else None
        except Exception:
            return None


def _extract_verdict(content: str) -> Optional[bool]:
    """
    Последнее упоминание TRUE/FALSE как отдельного слова в свободном тексте.
    Берём ПОСЛЕДНЕЕ — финальный вывод модели идёт после рассуждений.
    """
    if not content:
        return None
    matches = re.findall(r'\bTRUE\b|\bFALSE\b', content.upper())
    if not matches:
        return None
    return matches[-1] == 'TRUE'


def _parse_verdict(content: str) -> Optional[bool]:
    """Достаёт TRUE/FALSE сначала из JSON {"verdict": ...}, потом по подстроке."""
    if not content or not content.strip():
        return None

    parsed = _load_json_loose(content)
    if parsed is not None:
        v = str(parsed.get("verdict", "")).strip().upper()
        if v in ("TRUE", "FALSE"):
            return v == "TRUE"

    return _extract_verdict(content)


def _call_llm(system: str, user_message: str, image_url: str = '') -> Dict[str, Any]:
    """
    Обёртка над call_vsellm с логированием ошибок.

    Если есть image_url — мультимодальный вызов (текст + картинка),
    иначе — обычный текстовый вызов.

    Возвращает dict с полями:
      - answer / raw_text — текст ответа
      - raw — полный ответ API (для извлечения finish_reason, usage и т.д.)
    """
    try:
        if image_url:
            # Мультимодальный вызов с изображением
            result = call_vsellm(
                model=LLM_MODEL,
                service=LLM_ROUTER,
                system_prompt=system,
                user_text=user_message,
                image=True,
                image_url=image_url,
                temperature=LLM_TEMPERATURE,
                max_tokens=LLM_MAX_TOKENS,
                timeout_sec=LLM_TIMEOUT,
            )
        else:
            # Обычный текстовый вызов
            result = call_vsellm(
                model=LLM_MODEL,
                service=LLM_ROUTER,
                system_prompt=system,
                user_text=user_message,
                temperature=LLM_TEMPERATURE,
                max_tokens=LLM_MAX_TOKENS,
            )
        return result or {}
    except Exception as exc:
        logger.warning("call_vsellm failed: %s", exc)
        return {"answer": "", "raw_text": f"EXCEPTION: {exc}"}


def _parse_response_with_reasoning(result: Dict[str, Any]) -> Tuple[Optional[bool], str, Optional[str]]:
    """
    Парсит ответ LLM с поддержкой reasoning-моделей.

    Возвращает (match, raw_text, finish_reason).
    """
    # Сначала пробуем достать из структурированного ответа (для мультимодальных вызовов)
    raw = result.get('raw')
    if isinstance(raw, dict):
        choices = raw.get('choices', [])
        if choices:
            message = choices[0].get('message', {}) or {}
            finish_reason = choices[0].get('finish_reason')
            content = (message.get('content') or '').strip()
            reasoning = (message.get('reasoning_content') or '').strip()
            raw_text = content or reasoning

            # Пробуем JSON
            match = None
            try:
                parsed = json.loads(content)
                v = str(parsed.get('verdict', '')).strip().upper()
                if v in ('TRUE', 'FALSE'):
                    match = (v == 'TRUE')
            except (json.JSONDecodeError, AttributeError, TypeError):
                pass

            # Если не получилось — извлекаем последнее TRUE/FALSE
            if match is None:
                match = _extract_verdict(content)
            if match is None:
                match = _extract_verdict(reasoning)

            return match, raw_text, finish_reason

    # Запасной вариант: текстовый ответ из answer/raw_text
    content = str(result.get("answer") or result.get("raw_text") or "").strip()
    match = _parse_verdict(content)
    return match, content, None


def check_same_image(golden_text: str, answer_text: str, image_url: str = '') -> dict:
    """
    Сравнивает golden-описание с ответом разметчика + фактчек по изображению.

    Текст 1 — всегда golden, Текст 2 — всегда ответ разметчика.
    Если image_url пустой (или USE_IMAGE_FACTCHECK=False) — сравнение идёт без картинки,
    и все спорные теги считаются неподтверждёнными (так сказано в промпте).
    Если запрос с картинкой упал (не скачалась и т.п.) — повторяем без картинки
    только если IMAGE_FALLBACK_TO_TEXT=True, иначе возвращаем ошибку.

    Возвращает dict:
      - match: True | False | None
      - raw_response: str — полный ответ LLM
      - attempts: int — количество попыток
      - finish_reason: str | None
      - used_image: bool — была ли отправлена картинка
      - image_error: str — ошибка скачивания/обработки картинки (если была)
    """
    use_image = bool(USE_IMAGE_FACTCHECK and image_url)
    img_ref = ''
    image_error = ''

    if USE_IMAGE_FACTCHECK and not image_url:
        image_error = 'нет ссылки на изображение'
    elif use_image:
        try:
            img_ref = get_image_data_url(image_url)
        except Exception as e:
            image_error = f'{type(e).__name__}: {e}'
            if not IMAGE_FALLBACK_TO_TEXT:
                # Без тихого отката: ошибка картинки не должна превращаться
                # в «тег не подтверждён» и давать ложный FALSE
                return {
                    'match': None,
                    'raw_response': 'IMAGE ERROR: ' + image_error,
                    'attempts': 0,
                    'finish_reason': None,
                    'used_image': False,
                    'image_error': image_error,
                }
            use_image = False

    base_message = f"""Текст 1 (GOLDEN): {golden_text}
Текст 2 (ОТВЕТ разметчика): {answer_text}

{{image_note}}

Описывают ли эти тексты одно и то же? Выполни алгоритм и формат ответа из инструкции
(расчёт ШАГА 1, при необходимости ШАГ 2 с ФАКТ-ЧЕКОМ по изображению).
Последней строкой выведи ТОЛЬКО JSON: {{"verdict": "TRUE"}} или {{"verdict": "FALSE"}}."""

    last_raw = None
    last_finish_reason = None
    extra_hint = ''

    for attempt in range(1, LLM_MAX_RETRIES + 1):
        image_note = (
            'К сообщению приложено ИЗОБРАЖЕНИЕ, к которому относятся оба текста. '
            'Используй его для ФАКТ-ЧЕКА тегов ответа, попавших в противоречие.'
            if use_image else
            'Изображение НЕ приложено: фактчек недоступен, спорные теги ответа считаются НЕ ПОДТВЕРЖДЁННЫМИ.'
        )
        user_message = base_message.replace('{image_note}', image_note) + extra_hint

        try:
            response = _call_llm(SYSTEM_PROMPT, user_message, img_ref if use_image else '')
            match, raw_text, finish_reason = _parse_response_with_reasoning(response)
            last_raw, last_finish_reason = raw_text, finish_reason

            if match is not None:
                return {
                    'match': match,
                    'raw_response': raw_text,
                    'attempts': attempt,
                    'finish_reason': finish_reason,
                    'used_image': use_image,
                    'image_error': image_error,
                }

            extra_hint = (
                '\n\nВАЖНО: последней строкой верни ТОЛЬКО JSON {"verdict": "TRUE"} или '
                '{"verdict": "FALSE"}, без каких-либо иных символов.'
            )
        except Exception as e:
            # картинку при повторе НЕ выбрасываем: ошибка вызова != ошибка картинки
            last_raw = f'EXCEPTION: {type(e).__name__}: {e}'
            last_finish_reason = None
            continue

    reason_note = f' [finish_reason={last_finish_reason}]' if last_finish_reason else ''
    return {
        'match': None,
        'raw_response': (last_raw or '') + reason_note,
        'attempts': LLM_MAX_RETRIES,
        'finish_reason': last_finish_reason,
        'used_image': use_image,
        'image_error': image_error,
    }


def rule_verdict(
        golden_text: str,
        golden_broken: bool,
        answer_text: str,
        answer_broken: bool,
) -> Tuple[Optional[bool], str]:
    """Вердикт без LLM. Возвращает (verdict_same, verdict_source)."""
    answer_type = "broken" if answer_broken else ("text" if answer_text else "empty")
    golden_type = "broken" if golden_broken else "text"

    if answer_type == "empty":
        return None, "no_answer"
    if golden_type == "broken":
        return (answer_type == "broken"), "rule_broken"
    if answer_type == "broken":
        return False, "rule_broken"
    return None, "llm"


