def run_kandi_consist_mark_vs_gold(input_data: Any) -> Dict[str, Any]:
    """
    Принимает dict (или JSON-строку) с golden-описанием и ответом разметчика
    ОДНОГО и того же изображения.

    Пайплайн (перенесён из exam_vs_golden_analysis.ipynb):
      1. rule_verdict — вердикты без LLM для empty/broken случаев.
      2. Если оба текста валидны — check_same_image (LLM, правило D +
         правила A/B + ФАКТ-ЧЕК по изображению).

    Возвращает dict уже в схеме answers_vs_golden (той же, что и строки
    process_toloka_table / лист answers_vs_golden в ноутбуке), кроме полей
    status/quality/control_passed/task_id/assignment_id — они приходят от
    платформы отдельно и этой функцией не формируются:

      file_name, marker_id, golden_type, answer_type,
      golden_text, answer_text,
      verdict_same, verdict_label, verdict_source,
      llm_response, llm_attempts, llm_finish_reason,
      llm_used_image, llm_image_error
    """
    if isinstance(input_data, str):
        try:
            input_data = json.loads(input_data)
        except Exception:
            return {"error": "input_data is not valid JSON"}

    if not isinstance(input_data, dict):
        return {"error": "input_data must be a dict"}

    file_name = str(_get(input_data, "file_name", "INPUT:file_name", default="") or "").strip()
    marker_id = str(_get(input_data, "marker_id", "INPUT:marker_id", default="") or "").strip()

    golden_text_raw = str(
        _get(input_data, "golden_comment", "INPUT:golden_comment", "golden_text", default="") or ""
    ).strip()
    golden_broken = _flag(_get(input_data, "golden_broken", "INPUT:golden_broken", default=False))
    answer_text_raw = str(
        _get(input_data, "output_comment", "INPUT:output_comment", "answer_text", "comment", default="") or ""
    ).strip()
