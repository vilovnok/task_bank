# ─── Batch-обработка таблицы выгрузки Толоки ────────────────────────────────


def process_toloka_table(rows: list[dict]) -> list[dict]:
    """
    Batch-обработка выгрузки из Толоки.

    Вход — список строк-словарей с полями (минимально):
      - file_name (task_id в оригинальной выгрузке — имя изображения)
      - marker_id
      - status, quality, control_passed (опционально, прокидываются насквозь)
      - task_id, assignment_id (опционально, прокидываются насквозь)
      - INPUT:output_comment, INPUT:output_broken
      - INPUT:golden_comment, INPUT:golden_broken
      - INPUT:image_url / INPUT:output_image / GOLDEN:image (опционально, для фактчека)

    Выход — список строк-словарей с полями (в порядке как в примере):
      file_name, marker_id,
      golden_type, answer_type,
      golden_text, answer_text,
      verdict_same, verdict_label, verdict_source,
      llm_response, llm_attempts, llm_finish_reason,
      llm_used_image, llm_image_error,
      status, quality, control_passed, task_id, assignment_id

    verdict_label — человекочитаемое описание вердикта (4 состояния, как
    в исходном ноутбуке exam_vs_golden_analysis.ipynb):
      "нет ответа" (verdict_source == "no_answer") /
      "не оценено (LLM)" (LLM вызывалась, но не смогла распарсить вердикт
        после всех попыток — verdict_same is None) /
      "совпадает с golden" / "не совпадает с golden"
    golden_type / answer_type — "text" | "broken" | "empty"
    """
    results = []

    for row in rows:
        # ── Входные поля ──
        file_name = str(_get(row, "file_name", default="") or "").strip()
        marker_id = str(_get(row, "marker_id", default="") or "").strip()

        golden_text_raw = str(_get(row, "golden_comment", "INPUT:golden_comment", "golden_text", default="") or "").strip()
        golden_broken = _flag(_get(row, "golden_broken", "INPUT:golden_broken", default=False))
        answer_text_raw = str(_get(row, "output_comment", "INPUT:output_comment", "answer_text", "comment", default="") or "").strip()
        answer_broken = _flag(_get(row, "output_broken", "INPUT:output_broken", "answer_broken", "broken", default=False))
        image_url = str(_get(row, "image_url", "output_image", "INPUT:output_image", "GOLDEN:image", default="") or "").strip()

        # Прокидываемые насквозь (необязательные)
        status = str(_get(row, "status", default="") or "").strip()
        quality = _get(row, "quality", default=None)
        control_passed = _get(row, "control_passed", default=None)
        task_id = str(_get(row, "task_id", default="") or "").strip()
        assignment_id = str(_get(row, "assignment_id", default="") or "").strip()

        # ── Определяем типы (как в ноутбуке) ──
        answer_type_code = "broken" if answer_broken else ("text" if answer_text_raw else "empty")
        golden_type_code = "broken" if golden_broken else "text"

        golden_text = golden_text_raw if golden_type_code == "text" else ""
        answer_text = answer_text_raw if answer_type_code == "text" else ""

        # ── Rule-вердикт ──
        verdict_same_raw, verdict_source = rule_verdict(
            golden_text, golden_broken, answer_text, answer_broken
        )

        # ── Если нужен LLM — вызываем check_same_image ──
        llm_response = None
        llm_attempts = None
        llm_finish_reason = None
        llm_used_image = None
        llm_image_error = None

        if verdict_source == "llm":
            llm_result = check_same_image(golden_text, answer_text, image_url)
            verdict_same_raw = llm_result["match"]
            llm_response = llm_result.get("raw_response")
            llm_attempts = llm_result.get("attempts")
            llm_finish_reason = llm_result.get("finish_reason")
            llm_used_image = llm_result.get("used_image")
            llm_image_error = llm_result.get("image_error")

        # ── Формируем verdict_label (как в ноутбуке: 4 состояния) ──
        if verdict_source == "no_answer":
            verdict_label = "нет ответа"
        elif verdict_same_raw is None:
            verdict_label = "не оценено (LLM)"
        elif verdict_same_raw:
            verdict_label = "совпадает с golden"
        else:
            verdict_label = "не совпадает с golden"

        # ── Формируем выходную строку ──
        out_row = {
            "file_name": file_name,
            "marker_id": marker_id,
            "golden_type": golden_type_code,
            "answer_type": answer_type_code,
            "golden_text": golden_text,
            "answer_text": answer_text,
            "verdict_same": verdict_same_raw,
            "verdict_label": verdict_label,
            "verdict_source": verdict_source,
            "llm_response": llm_response,
            "llm_attempts": llm_attempts,
            "llm_finish_reason": llm_finish_reason,
            "llm_used_image": llm_used_image,
            "llm_image_error": llm_image_error,
            "status": status,
            "quality": quality,
            "control_passed": control_passed,
            "task_id": task_id,
            "assignment_id": assignment_id,
        }

        results.append(out_row)

    return results


# ─── Конвертация сырого export.xlsx платформы в формат answers_vs_golden ────
