def _bool_or_none(value: Any) -> Optional[bool]:
    """Приводит 'true'/'false'/'null'/True/False/None к bool | None."""
    if value is None:
        return None
    if isinstance(value, bool):
        return value
    text = str(value).strip().lower()
    if text in ("", "null", "none", "nan"):
        return None
    return text in ("true", "1", "1.0", "да")


def _parse_export_payload(row: dict) -> dict:
    """Достаёт и парсит JSON, зашитый в OUTPUT:final_user_prompt."""
    raw = _get(row, *_EXPORT_INPUT_JSON_KEYS, default=None)
    if not raw:
        return {}
    if isinstance(raw, dict):
        return raw
    try:
        parsed = json.loads(raw)
        return parsed if isinstance(parsed, dict) else {}
    except Exception:
        logger.warning("convert_export_to_answers_vs_golden: не удалось распарсить payload JSON")
        return {}


def convert_export_row_to_answers_vs_golden(row: dict) -> dict:
    """
    Конвертирует ОДНУ строку сырого export.xlsx (dict колонка -> значение)
    в одну строку формата answers_vs_golden. Вердикт берётся готовым из
    OUTPUT:*-колонок, LLM повторно не вызывается.
    """
    payload = _parse_export_payload(row)

    golden_broken = _flag(payload.get("golden_broken", False))
    answer_broken = _flag(payload.get("output_broken", False))
    golden_text_raw = str(payload.get("golden_comment", "") or "").strip()
    answer_text_raw = str(payload.get("output_comment", "") or "").strip()

    answer_type_code = "broken" if answer_broken else ("text" if answer_text_raw else "empty")
    golden_type_code = "broken" if golden_broken else "text"

    verdict_same = _bool_or_none(_get(row, *_EXPORT_VERDICT_SAME_KEYS, default=None))
    verdict_source = str(_get(row, *_EXPORT_VERDICT_SOURCE_KEYS, default="") or "").strip()

    if verdict_source == "no_answer":
        verdict_label = "нет ответа"
    elif verdict_same is None:
        verdict_label = "не оценено (LLM)"
    elif verdict_same:
        verdict_label = "совпадает с golden"
    else:
        verdict_label = "не совпадает с golden"

    return {
        "file_name": payload.get("file_name", _get(row, "file_name", default="")),
        "marker_id": payload.get("marker_id", _get(row, "marker_id", default="")),
        "golden_type": golden_type_code,
        "answer_type": answer_type_code,
        "golden_text": golden_text_raw if golden_type_code == "text" else "",
        "answer_text": answer_text_raw if answer_type_code == "text" else "",
        "verdict_same": verdict_same,
        "verdict_label": verdict_label,
        "verdict_source": verdict_source,
        "llm_response": _get(row, *_EXPORT_RAW_RESPONSE_KEYS, default=None),
        "llm_attempts": _get(row, *_EXPORT_ATTEMPTS_KEYS, default=None),
        "llm_finish_reason": _get(row, *_EXPORT_FINISH_REASON_KEYS, default=None),
        "llm_used_image": _bool_or_none(_get(row, *_EXPORT_USED_IMAGE_KEYS, default=None)),
        "llm_image_error": _get(row, *_EXPORT_IMAGE_ERROR_KEYS, default=None),
        "status": payload.get("status", _get(row, "status", default="")),
        "quality": payload.get("quality", _get(row, "quality", default=None)),
        "control_passed": _flag(payload.get("control_passed", _get(row, "control_passed", default=False))),
        # ВАЖНО: task_id/assignment_id верхнего уровня export.xlsx — это ID
        # exam-обёртки платформы, а НЕ то же самое, что в ноутбуке. Берём
        # "внутренние" id из payload, чтобы совпадало с answers_vs_golden.
        "task_id": payload.get("task_id"),
        "assignment_id": payload.get("assignment_id"),
    }


