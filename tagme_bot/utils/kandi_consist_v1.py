def _extract_visual_verdict(content: str):
    """Парсит VALID/INVALID и reason из ответа LLM."""
    if not content:
        return None, None

    # Ищем в JSON
    try:
        parsed = json.loads(content.strip())
        v = str(parsed.get('verdict', '')).strip().upper()
        r = str(parsed.get('reason', '')).strip()
        if v in ('VALID', 'INVALID'):
            return v, r if r else None
    except (json.JSONDecodeError, AttributeError, TypeError):
        pass

    # Ищем в тексте (только verdict, без reason)
    matches = re.findall(r'\b(VALID|INVALID)\b', content.upper())
    if matches:
        return matches[-1], None  # последнее упоминание

    return None, None


IMG_PREFETCH_TIMEOUT_SEC = 20

# Из входной строки нужны только эти поля; submitEnv_*/submitClicks_*/submitAmbient_*/
# border_*/image_N и прочее для работы скрипта не используются.
_KEEP_KEY_RE = re.compile(
    r"^(?:INPUT:)?(?:comment_\d+|marker_\d+|image|item_id|file_name|file_name_kandinsky)$"
)


def _filter_input(data: dict) -> dict:
    """Оставляет только необходимые для работы столбцы."""
    return {k: v for k, v in data.items() if _KEEP_KEY_RE.match(str(k))}


def _prefetch_image_as_data_url(image_url: str) -> str:
    """Скачивает картинку ОДИН раз и возвращает data:image/...;base64 URL.

    Байты не пережимаются: клиент (call_vsellm -> call_image) сам применяет
    динамическое сжатие, поэтому качество для модели не меняется. Для data URL
    клиент пропускает requests.get, повторных скачиваний нет. При ошибке
    возвращает исходный URL (клиент скачает сам, как раньше).
    """
    if not image_url or image_url.startswith("data:image/"):
        return image_url
    try:
        r = requests.get(image_url, timeout=IMG_PREFETCH_TIMEOUT_SEC, verify=False)
        r.raise_for_status()
        raw = r.content or b""
        if not raw:
            return image_url
        if raw[:8] == b"\x89PNG\r\n\x1a\n":
            mime = "image/png"
        elif raw[:4] == b"RIFF" and raw[8:12] == b"WEBP":
            mime = "image/webp"
        else:
            mime = "image/jpeg"
        return f"data:{mime};base64,{base64.b64encode(raw).decode('ascii')}"
    except Exception as e:
        logger.warning("prefetch image failed, fallback to URL: %s", e)
        return image_url


def check_visual_validity(image_url: str, tags: str) -> dict:
    """Проверяет соответствие тегов изображению через call_vsellm с картинкой."""

    if not image_url or image_url == 'nan':
        return {'verdict': 'VALID', 'reason': 'Нет URL изображения', 'raw_response': 'NO_IMAGE_URL',
                'attempts': 0, 'note': 'Нет URL, считаем валидным'}

    user_message = f"""ИЗОБРАЖЕНИЕ: см. выше

ТЕГИ РАЗМЕТЧИКА: {tags}

Соответствуют ли эти теги тому, что изображено на картинке?
Ответь СТРОГО в формате JSON: {{"verdict": "VALID", "reason": "..."}} или {{"verdict": "INVALID", "reason": "..."}}."""

    last_raw = None
    last_finish_reason = None

    for attempt in range(1, VISUAL_MAX_RETRIES + 1):
        try:
            logger.debug(f"check_visual_validity attempt {attempt}: image_url={image_url[:50] if image_url else 'EMPTY'}")

            # Вызываем call_vsellm с картинкой (как в kandi_consist_mark_vs_gold)
            response = _timed_call_vsellm(
                "visual_call_vsellm",
                model=VISUAL_MODEL,
                service=VISUAL_SERVICE,
                system_prompt=VISUAL_VALIDATION_SYSTEM_PROMPT,
                user_text=user_message,
                image=True,
                image_url=image_url,
                temperature=0.0,
                max_tokens=VISUAL_MAX_TOKENS,
            )

            # Парсим ответ из call_vsellm
            raw = response.get('raw') if isinstance(response, dict) else None
            if isinstance(raw, dict):
                choices = raw.get('choices', [])
                if choices:
                    message = choices[0].get('message', {}) or {}
                    finish_reason = choices[0].get('finish_reason')
                    content = (message.get('content') or '').strip()
                    reasoning = (message.get('reasoning_content') or '').strip()
                    last_raw = content or reasoning
                    last_finish_reason = finish_reason

                    verdict, reason = _extract_visual_verdict(content)
                    if verdict is None and reasoning:
                        verdict, reason = _extract_visual_verdict(reasoning)

                    if verdict is not None:
                        return {'verdict': verdict, 'reason': reason or '', 'raw_response': last_raw,
                                'attempts': attempt, 'finish_reason': finish_reason}

            # Если не получилось распарсить — пробуем answer/raw_text
            content = str(response.get("answer") or response.get("raw_text") or "").strip()
            if content:
                verdict, reason = _extract_visual_verdict(content)
                if verdict is not None:
                    return {'verdict': verdict, 'reason': reason or '', 'raw_response': content,
                            'attempts': attempt, 'finish_reason': None}

            user_message += (
                '\n\nВАЖНО: верни ТОЛЬКО JSON {"verdict": "VALID", "reason": "..."} или '
                '{"verdict": "INVALID", "reason": "..."}, без каких-либо иных символов.'
            )
        except Exception as e:
            logger.warning(f"check_visual_validity attempt {attempt} failed: {e}", exc_info=True)
            last_raw = f'EXCEPTION: {e}'
            last_finish_reason = None
            continue

    # Если не распарсилось — считаем VALID (не отбрасываем по техническим причинам)
    return {'verdict': 'VALID', 'reason': 'Не удалось распарсить ответ', 'raw_response': last_raw or 'NO_RESPONSE',
            'attempts': VISUAL_MAX_RETRIES, 'finish_reason': last_finish_reason,
            'note': 'Не удалось распарсить, считаем валидным'}


def validate_all_answers(input_data: dict) -> Tuple[List[dict], dict]:
    """Валидирует все 3 ответа визуально. Возвращает (valid_answers, validation_results).

    Args:
        input_data: dict с comment_1, comment_2, comment_3, marker_1, marker_2, marker_3, image

    Returns:
        (valid_answers, all_validation_results) где:
        - valid_answers: список {"pos": 1, "comment": "...", "marker_id": "..."}
        - all_validation_results: полная инфо о всех проверках для select_raw_response
    """
    image_url = _get(input_data, 'image', '')
    # Картинка одна на задание — скачиваем один раз, а не по разу на каждый ответ
    _t_pf = time.perf_counter()
    image_url = _prefetch_image_as_data_url(image_url) if image_url else image_url
    _tlog("image_prefetch", _t_pf,
          size_kb=round(len(image_url) / 1024.0) if image_url else 0,
          as_data_url=bool(image_url and image_url.startswith("data:")))
    valid_answers = []
    all_checks = {}

    # Валидируем все 3 ответа
    for i in range(1, 4):  # 1, 2, 3
        comment_key = f'comment_{i}'
        marker_key = f'marker_{i}'

        comment = _get(input_data, comment_key, '')
        marker_id = _get(input_data, marker_key, '')

        if not comment:
            continue

        # Проверяем соответствие тегов изображению
        _t_va = time.perf_counter()
        check_result = check_visual_validity(image_url, comment)
        _tlog(f"visual_answer_{i}", _t_va, verdict=check_result.get('verdict'),
              attempts=check_result.get('attempts'))
        verdict = check_result.get('verdict', 'VALID')

        all_checks[f'answer_{i}'] = {
            'verdict': verdict,
            'reason': check_result.get('reason', ''),
            'comment_preview': comment[:100],  # первые 100 символов для лога
            'attempts': check_result.get('attempts', 0)
        }

        # Добавляем в valid_answers только VALID ответы
        if verdict == 'VALID':
            valid_answers.append({
                'pos': i,
                'comment': comment,
                'marker_id': marker_id
            })

    return valid_answers, all_checks


def _with_visual_check(raw_response: Optional[str], validation_results: Optional[dict]) -> Optional[str]:
    """Добавляет результаты визуальной валидации (verdict/reason по каждому ответу)
    в select_raw_response как JSON, не меняя набор полей результата."""
    if not validation_results:
        return raw_response
    payload: Dict[str, Any] = {}
    if raw_response:
        try:
            parsed = json.loads(raw_response)
            payload = parsed if isinstance(parsed, dict) else {"select_raw": raw_response}
        except Exception:
            payload = {"select_raw": raw_response}
    payload["visual_validation"] = validation_results
    return json.dumps(payload, ensure_ascii=False)


def create_invalid_visual_result(row_data: dict, validation_results: dict) -> dict:
    """Создаёт результат, когда < 2 ответов прошли визуальную валидацию.

    Использует consensus_type = "INVALID_VISUAL" и сохраняет результаты всех проверок.
    """
    result = {}

    # Копируем метаданные
    for key in ['item_id', 'file_name', 'item_key']:
        if key in row_data:
            result[key] = row_data[key]

    # Победитель и проигравшие - пусто
    result['winner_text_corrected'] = ''
    result['winner_answer_raw'] = ''
    result['winner_marker_id'] = ''
    result['spell_changed'] = False

    # Консенсус-метрики
    result['consensus_type'] = 'INVALID_VISUAL'
    result['consensus_size'] = 0
    result['pairwise_verdicts'] = 'N/A - визуальная валидация не пройдена'
    result['n_candidates'] = 0
    result['select_fallback'] = False

    # Сохраняем результаты всех визуальных проверок
    result['select_raw_response'] = json.dumps({
        'visual_validation': validation_results,
        'note': 'Недостаточно валидных ответов для анализа консенсуса (требуется >= 2)'
    }, ensure_ascii=False)

    return result


def _get(data: dict, key: str, default=None):
    """Ищет ключ с префиксом INPUT: и без него."""
    for candidate in (key, f"INPUT:{key}", key.replace("INPUT:", "")):
        if candidate in data and data[candidate] not in (None, ""):
            return data[candidate]
    return default


def _load_json_loose(content: str) -> Optional[dict]:
    if not content:
        return None
    text = content.strip()

    # Убираем markdown-обёртку
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*", "", text)
        text = re.sub(r"\s*```$", "", text)

        # Пытаемся распарсить как есть
    try:
        parsed = json.loads(text.strip())
        return parsed if isinstance(parsed, dict) else None
    except Exception:
        pass

        # Ищем первый {...} блок
    m = re.search(r"\{.*\}", text, re.DOTALL)
    if not m:
        return None

    json_text = m.group()

    # 🔧 ФИКС: экранируем неэкранированные кавычки внутри значений
    # Заменяем ": "текст "кавычки" текст" на ": "текст \"кавычки\" текст"
    try:
        # Простое решение: заменяем " внутри значений на \"
        # Ищем паттерн: "key": "value с "внутренними" кавычками"
        fixed = re.sub(
            r':\s*"([^"]*)"([^"]*)"',  # находим ": "текст"ещё"
            lambda m: f': "{m.group(1)}\\"' + m.group(2).replace('"', '\\"') +
                      '"',
            json_text
        )
        parsed = json.loads(fixed)
        return parsed if isinstance(parsed, dict) else None
    except Exception:
        pass

    # Если и это не помогло - пытаемся через ast.literal_eval (для одинарных кавычек)
    try:
        import ast
        # Заменяем двойные на одинарные и пробуем
        single_quoted = json_text.replace('"', "'")
        parsed = ast.literal_eval(single_quoted)
        return parsed if isinstance(parsed, dict) else None
    except Exception:
        return None


def _parse_verdict(content: str) -> Optional[bool]:
    """Достаёт TRUE/FALSE сначала из JSON {"verdict": ...}, потом по подстроке."""
    if not content or not content.strip():
        return None

    parsed = _load_json_loose(content)
    if parsed is not None:
        v = str(parsed.get("verdict", "")).strip().upper()
        if v in ("TRUE", "FALSE"):
            return v == "TRUE"

    matches = re.findall(r"\bTRUE\b|\bFALSE\b", content.upper())
    if not matches:
        return None
    return matches[-1] == "TRUE"  # как в ноутбуке: финальный вывод — последнее упоминание


def _parse_choice(content: str, n_options: int) -> Optional[int]:
    """Достаёт номер варианта (1..n) сначала из JSON {"best": N}, потом по regex."""
    if not content or not content.strip():
        return None

    parsed = _load_json_loose(content)
    if parsed is not None:
        try:
            val = int(parsed.get("best"))
            if 1 <= val <= n_options:
                return val
        except (TypeError, ValueError):
            pass

    nums = [int(x) for x in re.findall(r"\d+", content)]
    for val in reversed(nums):  # финальный вывод обычно в конце
        if 1 <= val <= n_options:
            return val
    return None


def _parse_spell(content: str, original: str) -> Optional[str]:
    """Достаёт исправленный текст сначала из JSON {"text": ...}, иначе — сырой текст."""
    if not content or not content.strip():
        return None

    parsed = _load_json_loose(content)
    if parsed is not None:
        text = parsed.get("text")
        if isinstance(text, str) and text.strip():
            return text.strip()

    # фолбэк как в ноутбуке: модель вернула просто однострочный текст
    stripped = re.sub(r"^```(?:json)?|```$", "", content.strip()).strip()
    if len(stripped.splitlines()) == 1 and not stripped.startswith("{"):
        return stripped.strip('"') or None
    return None


def _call_llm(system: str, user_message: str, model: str, service: str, max_tokens: int,
              tag: str = "llm") -> Optional[str]:
    """Вызывает LLM через vsellm_client.call_vsellm."""
    from utils.vsellm_client import call_vsellm

    result = _timed_call_vsellm(
        f"{tag}_call_vsellm",
        model=model,
        service=service,
        system_prompt=system,
        user_text=user_message,
        temperature=LLM_TEMPERATURE,
        max_tokens=max_tokens,
    )
    answer = (result.get("answer") or result.get("raw_text") or "").strip() or None
    return answer


def _check_pair(comment_a: str, comment_b: str) -> Optional[bool]:
    """
    Проверяет согласованность пары через LLM (этап 1).
    Возвращает True/False, либо None, если вердикт не удалось распознать.
    """
    user_message = (
        f"Текст 1: {comment_a}\n"
        f"Текст 2: {comment_b}\n\n"
        f'Описывают ли эти тексты одно и то же?\n'
        f'Ответь СТРОГО в формате JSON: {{"verdict": "TRUE"}} или {{"verdict": "FALSE"}}.\n'
        f'Никакого текста до или после JSON.'
    )

    last_error = None
    for attempt in range(PAIR_MAX_RETRIES):
        try:
            content = _call_llm(CONSISTENCY_SYSTEM_PROMPT, user_message, PAIR_MODEL, PAIR_SERVICE, PAIR_MAX_TOKENS, tag="pair")
            if content is None:
                raise ValueError("Пустой ответ LLM")

            verdict = _parse_verdict(content)
            if verdict is None:
                raise ValueError(f"Не удалось распознать TRUE/FALSE: {content!r}")

            return verdict

        except Exception as e:
            last_error = e
            user_message += (
                '\n\nВАЖНО: верни ТОЛЬКО JSON {"verdict": "TRUE"} или '
                '{"verdict": "FALSE"}, без каких-либо иных символов.'
            )
            if attempt < PAIR_MAX_RETRIES - 1:
                time.sleep(LLM_RETRY_BACKOFF ** attempt)

    logger.warning("_check_pair: все попытки провалились: %s", last_error)
    return None


def _select_best(comments: List[str]) -> Dict[str, Any]:
    """
    Просит LLM выбрать лучший вариант из списка (этап 2, правила РКК).
    Возвращает {"choice": 0-based индекс, "raw_response": сырой ответ LLM
    (или None), "fallback": True, если пришлось взять вариант 0 из-за ошибки}.
    """
    n = len(comments)
    if n == 1:
        return {"choice": 0, "raw_response": "(единственный кандидат)", "fallback": False}

    lines = ["Варианты разметки одного изображения:", ""]
    for i, c in enumerate(comments, 1):
        lines.append(f"{i}. {c}")
    lines.append("")
    lines.append(f"Выбери номер (от 1 до {n}) варианта, который лучше всего "
                 f"соответствует инструкции проекта.")
    lines.append('Ответ строго в формате JSON: {"best": N}')
    user_message = "\n".join(lines)

    last_error = None
    last_content = None
    for attempt in range(SELECT_MAX_RETRIES):
        try:
            content = _call_llm(SELECT_SYSTEM_PROMPT, user_message, SELECT_MODEL, SELECT_SERVICE, SELECT_MAX_TOKENS, tag="select")
            last_content = content
            if content is None:
                raise ValueError("Пустой ответ LLM")

            choice = _parse_choice(content, n)
            if choice is None:
                raise ValueError(f"Не удалось распознать номер варианта: {content!r}")

            return {"choice": choice - 1, "raw_response": content, "fallback": False}  # 0-based

        except Exception as e:
            last_error = e
            if attempt < SELECT_MAX_RETRIES - 1:
                time.sleep(LLM_RETRY_BACKOFF ** attempt)

    # fallback как в ноутбуке: самое длинное (обычно самое полное) описание
    fallback_idx = max(range(n), key=lambda i: len(comments[i]))
    logger.warning("_select_best: все попытки провалились, fallback=самое длинное: %s", last_error)
    return {"choice": fallback_idx, "raw_response": last_content, "fallback": True}


def _fix_spelling(text: str) -> Dict[str, Any]:
    """
    Исправляет орфографию/пунктуацию текста-победителя без изменения смысла (этап 3).
    При ошибке возвращает исходный текст без изменений.
    """
    user_message = (
        f"Текст: {text}\n\n"
        f'Исправь орфографические и пунктуационные ошибки, не меняя состав и смысл.\n'
        f'Ответ строго в формате JSON: {{"text": "исправленный текст"}}.'
    )

    last_error = None
    for attempt in range(SPELL_MAX_RETRIES):
        try:
            content = _call_llm(SPELL_SYSTEM_PROMPT, user_message, SPELL_MODEL, SPELL_SERVICE, SPELL_MAX_TOKENS, tag="spell")
            if content is None:
                raise ValueError("Пустой ответ LLM")

            fixed = _parse_spell(content, text)
            if fixed is None:
                raise ValueError(f"Не распознан ответ корректора: {content!r}")

            return {"fixed": fixed, "changed": fixed.strip() != text.strip()}

        except Exception as e:
            last_error = e
            if attempt < SPELL_MAX_RETRIES - 1:
                time.sleep(LLM_RETRY_BACKOFF ** attempt)

    logger.warning("_fix_spelling: все попытки провалились, оставляем исходный текст: %s", last_error)
    return {"fixed": text, "changed": False}


def _match_to_edge(match: Optional[bool]) -> bool:
    """Трактует вердикт пары как ребро графа консенсуса (True = согласованы)."""
    if match is None:
        return TREAT_NONE_AS_MATCH
    return bool(match)


def _build_clusters(n: int, edges: List[Tuple[int, int]]) -> List[List[int]]:
    """Union-Find по TRUE-рёбрам. Возвращает список кластеров (списки позиций),
    отсортированный по убыванию размера."""
    parent = list(range(n))

    def find(x: int) -> int:
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(a: int, b: int) -> None:
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[max(ra, rb)] = min(ra, rb)

    for a, b in edges:
        union(a, b)

    groups: Dict[int, List[int]] = {}
    for pos in range(n):
        groups.setdefault(find(pos), []).append(pos)
    return sorted(groups.values(), key=lambda c: (-len(c), c[0]))


