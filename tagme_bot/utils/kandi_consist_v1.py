def _run_kandi_consist_v1_impl(input_data: Any, enable_visual_validation: bool = True) -> Dict[str, Any]:
    """
    Принимает dict (или JSON-строку) с полями file_name_kandinsky, image,
    marker_1..N, comment_1..N.

    Пайплайн (перенесён из consensus_pipeline.ipynb):
      0. (НОВОЕ) Визуальная валидация всех ответов через LLM.
         Если < 2 ответов валидны → возвращает INVALID_VISUAL результат.
      1. Попарное сравнение описаний (TRUE/FALSE) — консистентность.
      2. Кластеризация по TRUE-рёбрам (Union-Find) — консенсус-кластер.
      3. Выбор победителя из кандидатов консенсус-кластера (правила РКК).
      4. Исправление орфографии победившего описания.

    Args:
        input_data: dict с file_name_kandinsky, image (ОБЯЗАТЕЛЕН), marker_1..3, comment_1..3
        enable_visual_validation: включить визуальную валидацию (по умолчанию True)

    Возвращает обогащённый dict с полями match_i_j, consensus_type,
    candidates, best_description, winner_text, winner_text_corrected,
    spell_changed, select_raw_response (с visual check info).
    """
    if isinstance(input_data, str):
        try:
            input_data = json.loads(input_data)
        except Exception:
            return {"error": "input_data is not valid JSON"}

    if not isinstance(input_data, dict):
        return {"error": "input_data must be a dict"}

    # Выбрасываем лишние столбцы (submitClicks_*, submitEnv_*, ...)
    input_data = _filter_input(input_data)

    # Собираем комментарии (comment_1, comment_2, ...) и marker_id (marker_1, marker_2, ...)
    comments: List[str] = []
    markers: List[str] = []
    idx = 1
    while True:
        val = _get(input_data, f"comment_{idx}")
        if val is None:
            break
        comments.append(str(val).strip())
        markers.append(str(_get(input_data, f"marker_{idx}", default="") or "").strip())
        idx += 1

    if len(comments) < 2:
        return {"error": f"Нужно минимум 2 комментария, найдено: {len(comments)}"}

    n = len(comments)

    # ── ЭТАП 0: Визуальная валидация всех ответов ───────────────────────────
    validation_results = None  # попадёт в select_raw_response, даже если все ответы VALID
    if enable_visual_validation:
        try:
            _t_s0 = time.perf_counter()
            try:
                valid_answers, validation_results = validate_all_answers(input_data)
            finally:
                _tlog("stage0_visual", _t_s0)

            # Если < 2 валидных ответов → отклоняем изображение
            if len(valid_answers) < 2:
                logger.warning("kandi_consist_v1: визуальная валидация провалена - %d из %d ответов валидны",
                               len(valid_answers), n)

                # Подготавливаем item_key и file_name для результата
                item_key = _get(input_data, 'item_id') or _get(input_data, 'file_name_kandinsky') or 'unknown'
                file_name = _get(input_data, 'file_name') or _get(input_data, 'file_name_kandinsky') or ''

                result = create_invalid_visual_result(
                    {'item_id': item_key, 'file_name': file_name, 'item_key': item_key},
                    validation_results
                )
                valid_pos = {ans['pos'] - 1 for ans in valid_answers}
                rejected = [i for i in range(n) if i not in valid_pos]
                for k, pos in enumerate(rejected, 1):
                    result[f'loser_answer_{k}'] = comments[pos]
                    result[f'loser_marker_{k}'] = markers[pos]
                    result[f'loser_{k}_in_consensus'] = False
                return result

            # Отфильтровываем comments и markers - берём только валидные
            valid_positions = [ans['pos'] - 1 for ans in valid_answers]  # 0-indexed
            comments = [comments[i] for i in valid_positions]
            markers = [markers[i] for i in valid_positions]
            n = len(comments)

            logger.info("kandi_consist_v1: визуальная валидация пройдена - %d из %d ответов валидны",
                        len(valid_answers), len(validation_results))

        except Exception as e:
            logger.error("kandi_consist_v1: ошибка при визуальной валидации: %s", e, exc_info=True)
            # Если визуальная валидация сломалась - продолжаем без неё
            pass

    # ── 1. Этап 1: проверка всех пар (последовательно) ───────────────────────
    # ВАЖНО: этот скрипт — обработчик ОДНОЙ строки (одного изображения) за
    # вызов, как и kandi_consist_mark_vs_gold.py. В ноутбуке ThreadPoolExecutor
    # запускался один раз НА ВСЮ ТАБЛИЦУ (сотни/тысячи пар со всех изображений
    # сразу), поэтому там параллелизм был оправдан. Здесь же на один вызов
    # приходится всего 1–3 пары одного изображения — параллелить внутри
    # одного вызова нечего, а если платформа и так вызывает бота параллельно
    # на разных строках, ThreadPoolExecutor внутри каждого вызова только
    # плодит лишние потоки и параллельные запросы к LLM поверх этого.
    pairs = list(combinations(range(n), 2))
    match_by_pair: Dict[Tuple[int, int], Optional[bool]] = {}
    pair_results: Dict[str, int] = {}

    _t_s1 = time.perf_counter()
    for i, j in pairs:
        key = f"match_{i + 1}_{j + 1}"
        _t_p = time.perf_counter()
        try:
            verdict = _check_pair(comments[i], comments[j])
        except Exception as e:
            logger.warning("pair %s_%s error: %s", i + 1, j + 1, e)
            verdict = None
        _tlog(f"pair_{i + 1}_{j + 1}", _t_p, verdict=verdict)
        match_by_pair[(i, j)] = verdict
        pair_results[key] = -1 if verdict is None else int(verdict)
    _tlog("stage1_pairs", _t_s1, pairs=len(pairs))

    match_count = sum(1 for v in pair_results.values() if v == 1)
    total_pairs = sum(1 for v in pair_results.values() if v != -1)
    consistency = round(match_count / total_pairs, 4) if total_pairs > 0 else 0.0

    # ── 2. Этап 1.5: кластеризация по TRUE-рёбрам (консенсус) ────────────────
    edges = [(i, j) for (i, j), v in match_by_pair.items() if _match_to_edge(v)]
    clusters = _build_clusters(n, edges)
    main_cluster = clusters[0]

    if len(main_cluster) == n:
        consensus_type = "full"
    elif len(main_cluster) >= 2:
        consensus_type = "majority"
    else:
        consensus_type = "none"

    if consensus_type == "none":
        candidate_positions = list(range(n)) if NO_CONSENSUS_STRATEGY == "skip" else []
    else:
        candidate_positions = main_cluster

    # ── 3. Строка pairwise_verdicts вида "1-2:TRUE, 1-3:TRUE, 2-3:FALSE" ────
    # '?' в конце — вердикт пары не удалось распознать (match_by_pair=None)
    pairwise_verdicts = ", ".join(
        f"{i + 1}-{j + 1}:{'TRUE' if _match_to_edge(match_by_pair[(i, j)]) else 'FALSE'}"
        f"{'?' if match_by_pair[(i, j)] is None else ''}"
        for i, j in pairs
    )

    # ── 4. Метаданные изображения (пробрасываем как есть) ───────────────────
    item_id = str(_get(input_data, "item_id", default="") or "").strip()
    file_name = str(_get(input_data, "file_name", default="") or _get(input_data, "file_name_kandinsky", default="") or "").strip()
    item_key = item_id or file_name

    output: Dict[str, Any] = {
        "item_id": item_id,
        "file_name": file_name,
        "item_key": item_key,
    }

    if not candidate_positions:
        # NO_CONSENSUS_STRATEGY == 'skip': нет консенсуса, победителя не выбираем
        output["winner_answer"] = None
        output["winner_answer_raw"] = None
        output["winner_marker_id"] = None
        output["spell_changed"] = False
        output["consensus_type"] = consensus_type
        output["consensus_size"] = len(main_cluster)
        output["pairwise_verdicts"] = pairwise_verdicts
        output["n_candidates"] = 0
        output["select_fallback"] = False
        output["select_raw_response"] = _with_visual_check(None, validation_results)

        logger.info(
            "kandi_consist_v1: item=%s pairs=%s consensus=%s -> skipped (no consensus)",
            item_key, pair_results, consensus_type,
        )
        return output

    # ── 5. Этап 2: выбор победителя среди кандидатов консенсус-кластера ─────
    candidate_texts = [comments[p] for p in candidate_positions]
    _t_s2 = time.perf_counter()
    select_res = _select_best(candidate_texts)
    _tlog("stage2_select", _t_s2, candidates=len(candidate_texts), fallback=select_res["fallback"])
    winner_pos = candidate_positions[select_res["choice"]]
    winner_text_raw = comments[winner_pos]
    winner_marker_id = markers[winner_pos]

    # ── 6. Этап 3: исправление орфографии победителя ────────────────────────
    if SPELL_ENABLED:
        _t_s3 = time.perf_counter()
        spell_res = _fix_spelling(winner_text_raw)
        _tlog("stage3_spell", _t_s3, changed=spell_res["changed"])
        winner_answer = spell_res["fixed"]
        spell_changed = spell_res["changed"]
    else:
        winner_answer = winner_text_raw
        spell_changed = False

    # ── 7. Проигравшие (loser_answer_i / loser_marker_i / loser_i_in_consensus) ──
    losers = [pos for pos in range(n) if pos != winner_pos]
    for i, pos in enumerate(losers, 1):
        output[f"loser_answer_{i}"] = comments[pos]
        output[f"loser_marker_{i}"] = markers[pos]
        output[f"loser_{i}_in_consensus"] = pos in main_cluster

    output["winner_text_corrected"] = winner_answer
    output["winner_answer_raw"] = winner_text_raw
    output["winner_marker_id"] = winner_marker_id
    output["spell_changed"] = spell_changed
    output["consensus_type"] = consensus_type
    output["consensus_size"] = len(main_cluster)
    output["pairwise_verdicts"] = pairwise_verdicts
    output["n_candidates"] = len(candidate_positions)
    output["select_fallback"] = select_res["fallback"]
    output["select_raw_response"] = _with_visual_check(select_res["raw_response"], validation_results)
    output['token_stats'] = {
        'total_requests': token_stats['total_requests'],
        'total_tokens': token_stats['total_tokens'],
        'prompt_tokens': token_stats['total_prompt_tokens'],
        'completion_tokens': token_stats['total_completion_tokens']
    }

    logger.info(
        "kandi_consist_v1: item=%s pairs=%s consensus=%s winner_marker=%s spell_changed=%s",
        item_key, pair_results, consensus_type, winner_marker_id, spell_changed,
    )

    return output


