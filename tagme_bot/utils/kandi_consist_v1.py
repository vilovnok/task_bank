class _StepTimer:
    """Копит шаги одного задания (одного вызова run_kandi_consist_v1)."""

    def __init__(self, item_label: str):
        self.item_label = item_label
        self.t0 = time.perf_counter()
        self.steps: List[Tuple[str, float]] = []

    def add(self, name: str, seconds: float) -> None:
        self.steps.append((name, seconds))

    def log_summary(self) -> None:
        total = time.perf_counter() - self.t0
        stages = [(n, d) for n, d in self.steps if n.startswith("stage")]
        calls = [d for n, d in self.steps if n.endswith("_call_vsellm")]
        calls_sum = sum(calls)
        leaf = [(n, d) for n, d in self.steps
                if not n.startswith("stage") and not n.startswith("visual_answer_")]
        slowest = sorted(leaf, key=lambda x: -x[1])[:5]
        logger.info(
            "[TIMING] item=%s SUMMARY total=%.2fs | %s | call_vsellm: %d calls, %.2fs "
            "(%.0f%% of total) | outside call_vsellm: %.2fs | slowest: %s",
            self.item_label, total,
            " ".join(f"{n}={d:.2f}s" for n, d in stages) or "no stages",
            len(calls), calls_sum, (calls_sum / total * 100.0) if total > 0 else 0.0,
            max(total - calls_sum, 0.0),
            ", ".join(f"{n}={d:.2f}s" for n, d in slowest) or "-",
            )


def _tlog(name: str, t_start: float, **extra: Any) -> float:
    """Логирует длительность шага (t_start — time.perf_counter() в его начале)."""
    dt = time.perf_counter() - t_start
    timer = _TIMER_VAR.get()
    label = timer.item_label if timer else "-"
    if timer:
        timer.add(name, dt)
    extra_str = (" " + " ".join(f"{k}={v}" for k, v in extra.items())) if extra else ""
    logger.info("[TIMING] item=%s step=%s %.2fs%s", label, name, dt, extra_str)
    return dt


def _timed_call_vsellm(tag: str, **kwargs: Any) -> Dict[str, Any]:
    """call_vsellm с замером времени + учёт токенов."""
    t = time.perf_counter()
    ok = False
    try:
        result = call_vsellm(**kwargs)
        ok = True

        # Учёт токенов
        usage = result.get('usage') or {}
        if usage:
            token_stats['total_prompt_tokens'] += usage.get('prompt_tokens',
                                                            0) or 0
            token_stats['total_completion_tokens'] += usage.get('completion_tokens', 0) or 0
            token_stats['total_tokens'] += usage.get('total_tokens', 0) or 0
            token_stats['total_requests'] += 1

        return result
    finally:
        _tlog(tag, t, ok=ok, model=kwargs.get("model"))


def _guess_item_label(input_data: Any) -> str:
    """Короткая метка задания для логов: item_id / file_name / начало имени картинки."""
    try:
        if isinstance(input_data, str):
            input_data = json.loads(input_data)
        if isinstance(input_data, dict):
            for k in ("item_id", "file_name", "file_name_kandinsky"):
                v = _get(input_data, k)
                if v:
                    return str(v)
            img = _get(input_data, "image")
            if img and not str(img).startswith("data:"):
                return str(img).split("?")[0].rstrip("/").rsplit("/", 1)[-1][:12]
    except Exception:
        pass
    return "unknown"


