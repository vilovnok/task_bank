def _extract_control(input_data: Any) -> Tuple[bool, Any, Optional[str]]:
    """
    Достаёт поле control из входной строки (с префиксом INPUT: или без).
    Возвращает (is_control, control_raw, control_comment):
      is_control      — есть ли непустое поле control (т.е. это контрольное задание);
      control_raw     — значение поля как пришло (пробрасывается в результат без изменений);
      control_comment — эталонный текст control.comment (None, если извлечь не удалось).
    Поддерживаются: dict, JSON-строка с объектом, плоская колонка control.comment /
    control_comment, а также просто строка (тогда она и есть эталонный комментарий).
    """
    if isinstance(input_data, str):
        try:
            input_data = json.loads(input_data)
        except Exception:
            return False, None, None
    if not isinstance(input_data, dict):
        return False, None, None

    control_raw = _get(input_data, "control")
    if control_raw is None or (isinstance(control_raw, float) and control_raw != control_raw):
        return False, None, None  # нет поля / пустая ячейка (NaN) — основное задание
    if isinstance(control_raw, str) and not control_raw.strip():
        return False, None, None

    ctrl = control_raw
    if isinstance(ctrl, str):
        try:
            parsed = json.loads(ctrl)
            ctrl = parsed
        except Exception:
            parsed = _load_json_loose(ctrl)
            if parsed is not None:
                ctrl = parsed

    comment = None
    if isinstance(ctrl, dict):
        comment = ctrl.get("comment")
    elif isinstance(ctrl, str):
        comment = ctrl  # control — просто текст эталона
    if comment is None:
        comment = _get(input_data, "control.comment") or _get(input_data, "control_comment")

    comment = str(comment).strip() if comment not in (None, "") else None
    return True, control_raw, comment


def _evaluate_control(input_data: Any, control_comment: Optional[str]) -> Dict[str, bool]:
    """
    Оценивает comment_1..3 на соответствие control.comment (тот же LLM-судья
    попарного сравнения, что и на этапе 1). Всегда оценивает ИСХОДНЫЕ комментарии,
    независимо от результата визуальной валидации и консенсуса.
    Результат: {"marker_i_control_passed": True/False}; False — комментария нет
    или нет эталона.
    """
    if isinstance(input_data, str):
        try:
            input_data = json.loads(input_data)
        except Exception:
            input_data = {}

    res: Dict[str, bool] = {}
    for i in range(1, CONTROL_MAX_COMMENTS + 1):
        key = f"marker_{i}_control_passed"
        comment = _get(input_data, f"comment_{i}")
        if control_comment is None or comment is None:
            res[key] = False
            continue
        _t = time.perf_counter()
        try:
            verdict = _check_pair(str(comment).strip(), control_comment)
        except Exception as e:
            logger.warning("control check %s error: %s", i, e)
            verdict = None
        _tlog(f"control_{i}", _t, verdict=verdict)
        res[key] = CONTROL_NONE_AS_PASSED if verdict is None else bool(verdict)
    return res


def run_kandi_consist_v1(input_data: Any, enable_visual_validation: bool = True) -> Dict[str, Any]:
    """Обёртка с таймингами: логирует каждый шаг ([TIMING] ... step=...) и итог (SUMMARY).
    Логика пайплайна — в _run_kandi_consist_v1_impl (описание выше).
    Для контрольных заданий (есть INPUT:control) дополнительно пробрасывает control
    и добавляет marker_{1,2,3}_control_passed."""
    timer = _StepTimer(_guess_item_label(input_data))
    token = _TIMER_VAR.set(timer)
    logger.info("[TIMING] item=%s START", timer.item_label)
    try:
        is_control, control_raw, control_comment = _extract_control(input_data)

        if is_control:
            # Контрольное задание: никаких сравнений ответов между собой
            # (ни визуальной валидации, ни попарного консенсуса, ни выбора, ни спеллчекера).
            # Только сравнение каждого comment_i с control.comment.
            data = input_data
            if isinstance(data, str):
                try:
                    data = json.loads(data)
                except Exception:
                    return {"error": "input_data is not valid JSON"}
            if not isinstance(data, dict):
                return {"error": "input_data must be a dict"}

            item_id = str(_get(data, "item_id", default="") or "").strip()
            file_name = str(_get(data, "file_name", default="")
                            or _get(data, "file_name_kandinsky", default="") or "").strip()
            result: Dict[str, Any] = {
                "item_id": item_id,
                "file_name": file_name,
                "item_key": item_id or file_name,
                "control": control_raw,  # в неизменном виде
            }
            if control_comment is None:
                logger.warning("kandi_consist_v1: control есть, но control.comment не найден")
            _t_c = time.perf_counter()
            try:
                result.update(_evaluate_control(data, control_comment))
            finally:
                _tlog("stage_control", _t_c)
            return result

        result = _run_kandi_consist_v1_impl(input_data, enable_visual_validation)
        return result
    finally:
        timer.log_summary()
        _TIMER_VAR.reset(token)