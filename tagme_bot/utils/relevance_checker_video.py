def clean_json_text(text: str) -> str:
    text = text.strip()

    if text.startswith("```"):
        text = text.strip("`")

        # иногда формат ```json\n{...}
        if text.lower().startswith("json"):
            text = text[4:].strip()

    return text.strip()


def check_forbidden_words(text: str, forbidden_words: set = None) -> str | None:
    if not text:
        return None

    # Если не передан список, используем дефолтный
    # if forbidden_words is None:
    #     forbidden_words = FORBIDDEN_WORDS

    text_lower = text.lower()
    words = re.findall(r"[а-яёa-z]+", text_lower)

    for word in words:
        word = word.strip(".,!?;:()[]{}\"'")

        if word in forbidden_words:
            logger.info(f"[RELEVANCE] Найдено запрещённое слово: '{word}'")
            return word

    for forbidden in forbidden_words:
        if " " in forbidden and forbidden in text_lower:
            logger.info(f"[RELEVANCE] Найдена запрещённая фраза: '{forbidden}'")
            return forbidden

    return None


def check_direction_words(text: str) -> tuple[bool, list[str]]:
    """
    Проверяет наличие слов направления в тексте.
    Возвращает: (has_direction_words: bool, found_words: list[str])
    """
    if not text:
        return False, []

    text_lower = text.lower()
    words = re.findall(r"[а-яёa-z]+", text_lower)

    found_words = []
    for word in words:
        word_clean = word.strip(".,!?;:()[]{}\"'")
        if word_clean in DIRECTION_WORDS:
            found_words.append(word_clean)

    # Удаляем дубликаты, но сохраняем порядок
    found_words = list(dict.fromkeys(found_words))

    return len(found_words) > 0, found_words


def check_relevance_with_giga(
        text: str,
        instruction: str,
        model: str | None = None,
        temperature: float = 0.75,
        max_tokens: int = 1000,
) -> Dict[str, Any]:
    if model is None:
        model = DEFAULT_RELEVANCE_MODEL
        logger.info(f"RELEVANCE USING MODEL: {model}")

    try:
        usage = {}

        # ===== если модель из VSELLM =====
        if model in VSELLM_MODELS:
            logger.info("RELAVANCE VSELLM PROXY")

            messages = []
            if instruction:
                messages.append({"role": "system", "content": instruction})
            messages.append({"role": "user", "content": text})

            result = call_vsellm(
                model=model,
                system_prompt=instruction,
                messages=messages,
                temperature=temperature,
                max_tokens=max_tokens,
                image=False,
                video=False,
            )

            usage = result.get("usage") or {}
            raw_answer = (result.get("answer") or "").strip()

        # ===== иначе GIGA =====
        else:
            messages = [
                {"role": "system", "content": instruction},
                {"role": "user", "content": text}
            ]

            result = call_giga_models(
                model=model,
                messages=messages,
                temperature=temperature,
                max_tokens=max_tokens,
                extract_think=False,
            )

            usage = result.get("usage") or {}
            raw_answer = (result.get("answer") or "").strip()

        logger.info(f"[RELEVANCE] Model '{model}' ответ: '{raw_answer}'")
        logger.info(f"[RELEVANCE] Usage: {usage}")

        # ===== JSON parsing =====
        try:
            cleaned = clean_json_text(raw_answer)
            parsed = json.loads(cleaned)

            if parsed.get("correct") == "notrelevant":
                return {
                    "result": "notrelevant",
                    "text": parsed.get("text"),
                    "model_used": model,
                    "temperature": temperature,
                    "usage": usage,
                }

            if parsed.get("correct") == "relevant":
                return {
                    "result": "relevant",
                    "text": None,
                    "model_used": model,
                    "temperature": temperature,
                    "usage": usage,
                }

        except Exception:
            pass

        answer = raw_answer.lower()

        if "notrelevant" in answer or "not relevant" in answer or "нерелевант" in answer:
            return {
                "result": "notrelevant",
                "text": None,
                "model_used": model,
                "temperature": temperature,
                "usage": usage,
            }

        if "relevant" in answer or "релевант" in answer:
            return {
                "result": "relevant",
                "text": None,
                "model_used": model,
                "temperature": temperature,
                "usage": usage,
            }

        return {
            "result": "notrelevant",
            "text": None,
            "model_used": model,
            "temperature": temperature,
            "usage": usage,
        }

    except Exception as e:
        logger.error(f"[RELEVANCE] Ошибка при вызове модели {model}: {e}")
        return {
            "result": "notrelevant",
            "text": None,
            "model_used": model,
            "temperature": temperature,
            "usage": {},
        }


def check_relevance_video(
        text: str,
        instruction: str,
        model: DEFAULT_RELEVANCE_MODEL,
        temperature: float = 0.75,
        max_tokens: int = 1000,
        forbidden_words: set = None
) -> Dict[str, Any]:
    logger.info(f"[RELEVANCE] Начало проверки текста (длина: {len(text)} символов)")
    logger.info(f"[RELEVANCE] TEXT:\n{text}")
    logger.info(f"[RELEVANCE] INSTRUCTION:\n{instruction}")

    has_direction, direction_words = check_direction_words(text)
    logger.info(f"[RELEVANCE] Проверка слов направления: found={has_direction}, words={direction_words}")
    forbidden_word = check_forbidden_words(text, forbidden_words)

    if forbidden_word:
        logger.info("[RELEVANCE] Результат: notrelevant (найдены запрещённые слова)")
        return {
            "result": "notrelevant",
            "reason": "forbidden_words",
            "forbidden_word_found": True,
            "forbidden_word": forbidden_word,
            "giga_result": None,
            "final_decision_by": "script",
            "model_used": None,
            "temperature": None,
            "destination": has_direction,
            "direction_words": direction_words,
            "usage": {}
        }

    logger.info("[RELEVANCE] Запрещённые слова не найдены, проверяем через модель...")
    giga_data = check_relevance_with_giga(
        text=text,
        instruction=instruction,
        model=model,
        temperature=temperature,
        max_tokens=max_tokens,
    )

    logger.info(f"[RELEVANCE] Результат: {giga_data} (проверка GigaChat)")

    has_direction, direction_words = check_direction_words(text)
    logger.info(f"[RELEVANCE] Проверка слов направления: found={has_direction}, words={direction_words}")

    return {
        "result": giga_data.get("result"),
        "reason": "giga_check",
        "forbidden_word_found": bool(giga_data.get("text")),
        "forbidden_word": giga_data.get("text"),
        "giga_result": giga_data.get("result"),
        "final_decision_by": "model",
        "model_used": giga_data.get("model_used"),
        "temperature": giga_data.get("temperature"),
        "destination": has_direction,
        "direction_words": direction_words,
        "usage": giga_data.get("usage")
    }



